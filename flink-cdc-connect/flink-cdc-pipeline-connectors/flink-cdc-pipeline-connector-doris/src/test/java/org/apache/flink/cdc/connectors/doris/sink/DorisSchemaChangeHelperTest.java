package org.apache.flink.cdc.connectors.doris.sink;

import org.apache.doris.flink.catalog.doris.FieldSchema;
import org.apache.doris.flink.sink.schema.SchemaChangeHelper;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.NullSource;
import org.junit.jupiter.params.provider.ValueSource;

import static org.assertj.core.api.Assertions.assertThat;

/** Regression tests for schema evolution SQL generated by the Doris connector dependency. */
class DorisSchemaChangeHelperTest {

    @ParameterizedTest
    @NullSource
    @ValueSource(strings = {"", " ", "seed"})
    void testModifyColumnPreservesDefaultValue(String defaultValue) {
        FieldSchema field = new FieldSchema();
        field.setName("name");
        field.setTypeString("VARCHAR(128)");
        field.setComment("");
        field.setDefaultValue(defaultValue);

        String ddl = SchemaChangeHelper.buildModifyColumnDataTypeDDL("test_db.test_table", field);

        if (defaultValue == null) {
            assertThat(ddl).doesNotContain(" DEFAULT ");
        } else {
            assertThat(ddl).endsWith(" DEFAULT '" + defaultValue + "'");
        }
    }
}
